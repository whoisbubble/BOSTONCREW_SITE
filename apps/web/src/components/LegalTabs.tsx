export function LegalTabs() {
  const [activeId, setActiveId] = useState<LegalDocument['id']>('terms');
  const currentDocument = documents.find((document) => document.id === activeId) ?? documents[0];

  return (
    <section id="legal" className="legal-section">
      <div className="section-heading">
        <p className="eyebrow">Документы</p>
        <h2>Условия сервиса</h2>
      </div>

      <div className="legal-tabs" role="tablist" aria-label="Документы сервиса">
        {documents.map((document) => {
          const Icon = document.icon === 'terms' ? FileText : ShieldCheck;

          return (
            <button
              aria-controls={`panel-${document.id}`}
              aria-selected={activeId === document.id}
              className={activeId === document.id ? 'is-active' : ''}
              id={`tab-${document.id}`}
              key={document.id}
              onClick={() => setActiveId(document.id)}
              role="tab"
              type="button"
            >
              <Icon size={18} />
              <span>{document.title}</span>
            </button>
          );
        })}
      </div>

      <article
        aria-labelledby={`tab-${currentDocument.id}`}
        className="legal-panel"
        id={`panel-${currentDocument.id}`}
        role="tabpanel"
      >
        <h3>{currentDocument.title}</h3>
        {currentDocument.blocks.map((block) => (
          <section className="legal-block" key={block.title}>
            <h4>{block.title}</h4>
            {block.paragraphs.map((paragraph) => (
              <p key={paragraph}>{paragraph}</p>
            ))}
            {block.items && (
              <ul>
                {block.items.map((item) => (
                  <li key={item}>{item}</li>
                ))}
              </ul>
            )}
          </section>
        ))}
      </article>
    </section>
  );
}
